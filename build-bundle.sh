#!/usr/bin/env bash
# Build a single-file bundle that any agent can ingest (paste, upload, or attach).
#
#   ./build-bundle.sh            -> dist/tizen-lite.skill.md
#
# Included: the skill contract, the agent operating contract, the machine-readable manifest,
# and the four playbooks. Long-form docs stay in docs/ and are listed at the end.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="$ROOT/dist/tizen-lite.skill.md"
mkdir -p "$ROOT/dist"

{
  cat <<'HEADER'
<!--
  Tizen Lite — single-file skill bundle.
  Generated by build-bundle.sh; do not edit by hand.
  Paste this whole file into an agent, or attach it as a document.
  Machine-readable facts also exist at agent/manifest.json.
-->

HEADER

  cat <<'PART0'
# Part 0 — read this first if the file is all you have

This bundle is **text only**. It cannot run anything: every script it names lives in the repository.

| You have | Then |
|---|---|
| the repo on the host that drives the TV | `./scripts/tv-doctor.sh` → `./agent/audit.sh` → one playbook. You can act. |
| only this file (pasted into a chat) | You are **advising, not operating**. Say so, and ask for the facts below before proposing a cut. |

Facts you need before advising anything: TV model + year, Tizen/firmware version, whether the repo and the
root chain exist on a host, the TV's IP, whether Developer Mode is on with that host whitelisted, and which
apps the user actually uses (Prime/DRM, Art Mode, TV Plus, AirPlay, Samsung account).

Do **not** invent `sdb` commands, do not paste the unit names below as instructions without checking they
exist on that model year, and never quote the numbers in Part 3 as the user's own.

PART0

  cat "$ROOT/skills/tizen-lite/SKILL.md"

  printf '\n\n---\n\n# Part 2 — operating contract for the agent\n\n'
  printf '_This is the same text as AGENTS.md in the repository._\n\n'
  sed '1{/^# AGENTS.md/d}' "$ROOT/AGENTS.md"

  printf '\n\n---\n\n# Part 3 — machine-readable manifest\n\n'
  printf '```json\n'
  cat "$ROOT/agent/manifest.json"
  printf '\n```\n'

  printf '\n\n---\n\n# Part 4 — playbooks\n'
  for f in disable-a-unit remove-an-app diagnose-broken-feature reclaim-memory; do
    printf '\n## %s\n\n' "$f"
    cat "$ROOT/agent/playbooks/$f.md"
  done

  cat <<'FOOTER'

---

# Part 5 — not included, read from the repo when needed

| File | Why it is separate |
|---|---|
| `docs/rooting.md` | how root is obtained, compatibility, when it is not worth it |
| `docs/boot-and-startup.md` | boot queue, measuring time-to-launcher |
| `docs/debloat-modding.md` | ad/OTA/voice removal, TizenTube proxy fix |
| `docs/app-uninstall.md` | durable app removal and the load-bearing set |
| `docs/sdb-audit.md` | read-only audit of a retail set |
| `bin/`, `config/`, `scripts/` | the runnable tools and the editable state files |

Nothing here is a substitute for the Rule 0 audit on the actual TV: unit names and app ids differ
between model years, and a cut verified on one set is a hypothesis on another.
FOOTER
} > "$OUT"

# keep the Claude Code auto-discovered copy in sync with the source skill
mkdir -p "$ROOT/.claude/skills/tizen-lite"
cp "$ROOT/skills/tizen-lite/SKILL.md" "$ROOT/.claude/skills/tizen-lite/SKILL.md"

printf 'wrote %s (%s bytes, %s lines)\n' \
  "${OUT#"$ROOT"/}" "$(wc -c <"$OUT")" "$(wc -l <"$OUT")"
